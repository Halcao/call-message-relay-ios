func TestDCSEngine(t *testing.T) {
	// Table verified against ETSI TS 123 038 V18.0.0 clause 4 coding groups.
	cases := []struct {
		dcs  byte
		want Encoding
	}{
		// 00xx general data coding: bits 3-2 alphabet, bit 5 compression,
		// bit 4 class.
		{0x00, EncodingGSM7}, {0x04, Encoding8Bit}, {0x08, EncodingUCS2},
		{0x0C, EncodingGSM7}, // reserved -> assume GSM7
		{0x10, EncodingGSM7}, {0x14, Encoding8Bit}, {0x18, EncodingUCS2},
		{0x20, Encoding8Bit}, // compressed: raw preserved, never decoded
		{0x24, Encoding8Bit}, {0x34, Encoding8Bit},
		// 01xx automatic-deletion group: bits 5..0 coded exactly like 00xx.
		{0x40, EncodingGSM7}, {0x44, Encoding8Bit}, {0x48, EncodingUCS2},
		{0x4C, EncodingGSM7}, {0x60, Encoding8Bit}, {0x68, Encoding8Bit},
		// 1000..1011 reserved: spec requires assuming GSM 7 bit default.
		{0x80, EncodingGSM7}, {0x8C, EncodingGSM7}, {0xB8, EncodingGSM7},
		// 1100/1101 MWI text is GSM7; 1110 MWI text is UCS2.
		{0xC0, EncodingGSM7}, {0xC8, EncodingGSM7}, {0xD4, EncodingGSM7},
		{0xE0, EncodingUCS2}, {0xE8, EncodingUCS2},
		// 1111 data coding/message class: bit 2 selects 7-bit vs 8-bit.
		{0xF0, EncodingGSM7}, {0xF4, Encoding8Bit}, {0xF8, EncodingGSM7},
	}
	for _, tc := range cases {
		if got := dcsEncoding(tc.dcs); got != tc.want {
			t.Errorf("dcsEncoding(0x%02x) = %q, want %q", tc.dcs, got, tc.want)
		}
	}
}

func TestDecodeAutomaticDeletionDCSBinaryStaysBinary(t *testing.T) {
	// DCS 0x44 = 01xx automatic-deletion group with bits 3-2 = 01 (8-bit
	// data). Before the TS 23.038 group fix this fell through to GSM7 and
	// produced mojibake; it must stay raw hex.
	pdu := "07916131059010F104038116F100446201401202018A0548656C6C6F"
	decoded, err := DecodePDU(pdu)
	if err != nil {
		t.Fatal(err)
	}
	if decoded.Encoding != Encoding8Bit || decoded.Body != "48656c6c6f" {
		t.Fatalf("decoded = %#v, want 8bit raw hex", decoded)
	}
}
