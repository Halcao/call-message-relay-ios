func TestMultipartGSM7RoundTripPreservesBody(t *testing.T) {
	segments, err := EncodeSubmitSegments("+8613800138000", strings.Repeat("Hello {world} ", 20), 0x42)
	if err != nil {
		t.Fatal(err)
	}
	if len(segments) < 2 {
		t.Fatalf("expected multipart segments, got %d", len(segments))
	}
	for index, segment := range segments {
		decoded, err := DecodePDU(segment.PDU)
		if err != nil {
			t.Fatalf("segment %d: %v", index, err)
		}
		if decoded.Body != segment.Body {
			t.Fatalf("segment %d body = %q, want %q", index, decoded.Body, segment.Body)
		}
		if decoded.Encoding != EncodingGSM7 {
			t.Fatalf("segment %d encoding = %q", index, decoded.Encoding)
		}
	}
}

// Field-captured SMS-DELIVER shapes (2026-10-05). The GSM7 payloads are
// packed the standard way: the text septets start at the next septet
// boundary after the octet-aligned UDH. These fixtures are generated by an
// independent encoder, not this package, so encoder and decoder cannot
// silently share the same deviation.
func TestDecodeGSM7WithConcatenationUDH(t *testing.T) {
	pdu := "07916131059010F14405815405F100006201401202018A4B050003DD0303407474190467D7E7A079BE2D7EB341A8558A0532BFD9ECF7BD4C0689F3203ABA0C1ABFEB6EBA3C0F1ABFC96550D84D06C1D16F7719E4AEB7C565B90B"
	decoded, err := DecodePDU(pdu)
	if err != nil {
		t.Fatal(err)
	}
	want := " the plus symbol (+), followed by the country code and phone number."
	if decoded.Body != want {
		t.Fatalf("body = %q, want %q", decoded.Body, want)
	}
	if decoded.Encoding != EncodingGSM7 || decoded.Sender != "45501" {
		t.Fatalf("decoded = %#v", decoded)
	}
	if decoded.ConcatRef != 0xDD || decoded.PartNo != 3 || decoded.TotalParts != 3 {
		t.Fatalf("UDH metadata = %#v", decoded)
	}
}

