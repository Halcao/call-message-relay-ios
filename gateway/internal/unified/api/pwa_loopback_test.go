// Real-browser PWA audio loopback harness.
//
// This test runs the PRODUCTION PWA assets (served by the real
// internal/webui handler) against the real unified gateway API + production
// media implementation (internal/unified/media + Pion), with a fake cellular
// modem worker supplying/consuming PCMU. A real installed Edge (playwright-
// core, headless) drives the page with a synthetic microphone WAV and the
// real WebRTC/AudioContext stack; nothing about the media stack is mocked.
//
// It is opt-in because it needs a browser: set PWA_LOOPBACK=1 to run it.
// Playwright-core is located through PWA_HARNESS_NODE_MODULES or the
// opencode tooling directory.
//
// Evidence produced: direct path negotiates Opus and carries both directions;
// the WSS fallback carries PCMU both directions with 0xFF mute silence; the
// fallback keeps one microphone stream (single media owner); answer/hangup/
// mute lifecycle converges. Uplink is measured by decoding the PCMU actually
// received at the fake modem; downlink is measured on the browser's real
// remote track / real WebSocket binary frames.

