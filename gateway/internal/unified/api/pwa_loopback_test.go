type pwaHarnessResult struct {
	OK     bool                   `json:"ok"`
	Error  string                 `json:"error"`
	Checks []pwaHarnessCheck      `json:"checks"`
	Data   map[string]interface{} `json:"data"`
}

type pwaHarnessCheck struct {
	Name   string `json:"name"`
	OK     bool   `json:"ok"`
	Detail string `json:"detail"`
}

func TestPWABrowserLoopback(t *testing.T) {
	if os.Getenv("PWA_LOOPBACK") != "1" {
		t.Skip("set PWA_LOOPBACK=1 to run the real-browser PWA audio loopback harness")
	}
	if _, err := exec.LookPath("node"); err != nil {
		t.Skip("node not available for the browser harness")
	}
	nodeModules := os.Getenv("PWA_HARNESS_NODE_MODULES")
	if nodeModules == "" {
		nodeModules = filepath.Join(os.TempDir(), "opencode", "node_modules")
	}
	playwrightCore := filepath.Join(nodeModules, "playwright-core")
	if _, err := os.Stat(playwrightCore); err != nil {
		t.Skipf("playwright-core not found at %s", playwrightCore)
	}
	runner := filepath.Join("..", "..", "..", "..", "tools", "pwa-loopback", "run.js")
	if _, err := os.Stat(runner); err != nil {
		t.Fatalf("browser runner missing: %v", err)
	}
	pwaDir, err := filepath.Abs(filepath.Join("..", "..", "webui", "pwa"))
	if err != nil {
		t.Fatalf("pwa dir: %v", err)
	}

	stack, fake, cleanup := newPWALoopbackStack(t)
	defer cleanup()

	keyID, secret, err := stack.auth.CreateKey(context.Background(), "pwa-loopback", true)
	if err != nil {
		t.Fatalf("create enrollment key: %v", err)
	}
	fake.setAutoAnswer(true)
	fake.enableModemTone(1000) // downlink tone toward the browser

	outPath := os.Getenv("PWA_HARNESS_OUT")
	if outPath == "" {
		outPath = filepath.Join(t.TempDir(), "pwa-loopback-result.json")
	} else {
		_ = os.MkdirAll(filepath.Dir(outPath), 0o755)
	}
	cmd := exec.Command("node", runner)
	cmd.Dir = "."
	cmd.Env = append(os.Environ(),
		"PWA_HARNESS_URL="+stack.server.URL, // gitleaks:allow -- Synthetic loopback URL, with a runtime-generated test key below.
		"PWA_HARNESS_KEY="+keyID+"."+secret, // gitleaks:allow -- Key generated by the in-memory test gateway, not a stored credential.
		"PWA_HARNESS_OUT="+outPath,
		"PWA_HARNESS_PWA_DIR="+pwaDir,
		"PWA_PLAYWRIGHT_CORE="+playwrightCore,
	)
	var output bytes.Buffer
	cmd.Stdout = &output
	cmd.Stderr = &output
	runErr := cmd.Run()
	t.Logf("browser harness output:\n%s", output.String())
	if runErr != nil {
		// The result file carries the structured failure detail.
		if data, readErr := os.ReadFile(outPath); readErr == nil {
			var result pwaHarnessResult
			if json.Unmarshal(data, &result) == nil {
				for _, check := range result.Checks {
					if !check.OK {
						t.Errorf("FAIL %s :: %s", check.Name, check.Detail)
					}
				}
				t.Errorf("browser runner failed: %v (error=%s)", runErr, result.Error)
			}
		}
		t.Fatalf("browser runner failed: %v", runErr)
	}

	data, err := os.ReadFile(outPath)
	if err != nil {
		t.Fatalf("read harness result: %v", err)
	}
	var result pwaHarnessResult
	if err := json.Unmarshal(data, &result); err != nil {
		t.Fatalf("decode harness result: %v", err)
	}
	for _, check := range result.Checks {
		if check.OK {
			t.Logf("ok   - %s", check.Name)
		} else {
			t.Errorf("FAIL - %s :: %s", check.Name, check.Detail)
		}
	}
	if !result.OK {
		// Compact diagnostic dump: enough to see the media evidence even
		// when a check fails (never includes credentials).
		if data, err := json.Marshal(result.Data); err == nil && len(data) < 1<<20 {
			t.Logf("harness data: %s", data)
		}
		t.Fatalf("browser harness reported failure: %s", result.Error)
	}

	// Independent modem-side uplink evidence captured during the runner's
	// final unmuted window (the runner resets the window itself and reports
	// the decoded PCMU it receives from the gateway). This is the fake
	// cellular sink, not the browser.
	if report, ok := result.Data["finalUplink"].(map[string]interface{}); ok {
		value := func(key string) float64 {
			if v, ok := report[key].(float64); ok {
				return v
			}
			return 0
		}
		if frames := int(value("frames")); frames < 20 {
			t.Errorf("modem uplink continuity: only %d PCMU frames in the final window", frames)
		}
		if rms := value("rms"); rms < 500 {
			t.Errorf("modem uplink has no measurable PCM level: rms=%v", rms)
		}
		if gap := value("maxGapMs"); gap > 120 {
			t.Errorf("modem uplink continuity gap too large: %vms", gap)
		}
		t.Logf("modem uplink evidence: frames=%v rms=%v toneHz=%v tonePower=%v maxGapMs=%v",
			report["frames"], report["rms"], report["toneHz"], report["tonePower"], report["maxGapMs"])
	}

	if dumpDir := os.Getenv("PWA_DUMP_DIR"); dumpDir != "" {
		if id := fake.busiestAudioCall(); id != "" {
			_ = writePCM16Wav(filepath.Join(dumpDir, "modem-uplink.wav"), fake.uplinkPCM(id), 8000)
		}
	}
}

func writePCM16Wav(path string, pcm []int16, rate int) error {
	buf := make([]byte, 44+len(pcm)*2)
	copy(buf[0:], "RIFF")
	binary.LittleEndian.PutUint32(buf[4:], uint32(36+len(pcm)*2))
	copy(buf[8:], "WAVE")
	copy(buf[12:], "fmt ")
	binary.LittleEndian.PutUint32(buf[16:], 16)
	binary.LittleEndian.PutUint16(buf[20:], 1)
	binary.LittleEndian.PutUint16(buf[22:], 1)
	binary.LittleEndian.PutUint32(buf[24:], uint32(rate))
	binary.LittleEndian.PutUint32(buf[28:], uint32(rate*2))
	binary.LittleEndian.PutUint16(buf[32:], 2)
	binary.LittleEndian.PutUint16(buf[34:], 16)
	copy(buf[36:], "data")
	binary.LittleEndian.PutUint32(buf[40:], uint32(len(pcm)*2))
	for i, value := range pcm {
		binary.LittleEndian.PutUint16(buf[44+i*2:], uint16(value))
	}
	return os.WriteFile(path, buf, 0o600)
}

// newPWALoopbackStack mirrors production wiring: real store/auth/runtime/media
// with a fake worker line, self-hosted webpush sessions (the PWA cookie
// session), and the real PWA asset handler plus harness-only control routes.
func newPWALoopbackStack(t *testing.T) (*testStack, *fakeWorker, func()) {
	t.Helper()
	if os.Getenv("PWA_DEBUG_LOG") != "" {
		slog.SetLogLoggerLevel(slog.LevelDebug)
	}
	dir := t.TempDir()
	cfg := config.Default()
	cfg.Gateway.ID = "gw-pwa-harness"
	cfg.Gateway.Name = "PWA Harness"
	cfg.Gateway.DataDir = dir
	cfg.Gateway.Listen = "127.0.0.1:0"
	cfg.Voicemail.AudioRoot = filepath.Join(dir, "sd-missing", "voicemail")
	cfg.Voicemail.MountPoint = filepath.Join(dir, "sd-missing")
	cfg.Voicemail.ExpectedDevice = "/dev/mmcblk0"
	cfg.WebPush.Enabled = true

	fake := newFakeWorker("line1")
	tokenFile := filepath.Join(dir, "internal1.token")
	if err := os.WriteFile(tokenFile, []byte("test-internal-token"), 0o600); err != nil {
		t.Fatalf("write token: %v", err)
	}
	cfg.Lines = append(cfg.Lines, config.Line{
		ID: fake.LineID, Name: fake.LineID, WorkerURL: fake.server.URL,
		TokenFile: tokenFile, IdentityFile: filepath.Join(dir, "missing-identity.json"), Enabled: true,
	})
	if err := cfg.Validate(); err != nil {
		t.Fatalf("config: %v", err)
	}
	database, err := store.Open(filepath.Join(dir, "unified.sqlite"))
	if err != nil {
		t.Fatalf("store: %v", err)
	}
	if err := database.Migrate(context.Background()); err != nil {
		t.Fatalf("migrate: %v", err)
	}
	gatewayIdentity, err := identity.LoadOrCreate(filepath.Join(dir, "gateway.key"), cfg.Gateway.ID, cfg.Gateway.Name)
	if err != nil {
		t.Fatalf("identity: %v", err)
	}
	authService := auth.New(database, gatewayIdentity, time.Minute, time.Hour)
	bus := events.NewBus(database)
	engine, err := media.NewEngine()
	if err != nil {
		t.Fatalf("media engine: %v", err)
	}
	manager := runtime.NewManager(cfg, database, bus, authService, engine, nil)
	ctx, cancel := context.WithCancel(context.Background())
	if err := manager.Start(ctx); err != nil {
		t.Fatalf("manager start: %v", err)
	}
	keys, err := webpush.LoadOrCreateKeys(filepath.Join(dir, "vapid.key"))
	if err != nil {
		t.Fatalf("vapid keys: %v", err)
	}
	webPushManager := webpush.NewManager(database)
	webPushSender := &webpush.Sender{
		Subject:    "mailto:harness@localhost",
		PublicKey:  keys.PublicKey,
		PrivateKey: keys.PrivateKey,
		TTL:        30 * time.Second,
		Timeout:    5 * time.Second,
	}
	apiServer := NewServer(cfg, authService, database, bus, manager, gatewayIdentity)
	apiServer.WebPush = webPushManager
	apiServer.WebPushSender = webPushSender
	apiServer.VAPIDPublicKey = keys.PublicKey

	mux := http.NewServeMux()
	mux.Handle("/api/v2/", apiServer.Handler())
	mux.Handle("/pwa", webui.PWAHandler())
	mux.Handle("/pwa/", webui.PWAHandler())
	mux.HandleFunc("/harness/incoming", func(w http.ResponseWriter, r *http.Request) {
		var request struct {
			Peer string `json:"peer"`
		}
		_ = json.NewDecoder(r.Body).Decode(&request)
		if strings.TrimSpace(request.Peer) == "" {
			request.Peer = "+8613800000042"
		}
		callID := fmt.Sprintf("harness-in-%d", time.Now().UnixNano())
		fake.injectIncoming(callID, request.Peer)
		writeJSON(w, http.StatusOK, map[string]string{"id": callID, "peer": request.Peer})
	})
	mux.HandleFunc("/harness/modem/reset", func(w http.ResponseWriter, _ *http.Request) {
		fake.resetModemAudio()
		writeJSON(w, http.StatusOK, map[string]string{"status": "reset"})
	})
	mux.HandleFunc("/harness/modem/status", func(w http.ResponseWriter, _ *http.Request) {
		fake.mu.Lock()
		status := map[string]interface{}{
			"downlinkFrames": fake.downlinkFrames,
			"mediaSockets":   len(fake.mediaConns),
			"socketsOpened":  fake.mediasOpened,
			"toneHz":         fake.modemToneHz,
		}
		fake.mu.Unlock()
		writeJSON(w, http.StatusOK, status)
	})
	mux.HandleFunc("/harness/modem/uplink", func(w http.ResponseWriter, _ *http.Request) {
		fake.mu.Lock()
		ids := make([]string, 0, len(fake.calls))
		for id := range fake.calls {
			ids = append(ids, id)
		}
		fake.mu.Unlock()
		reports := make(map[string]modemAudioReport, len(ids))
		for _, id := range ids {
			reports[id] = fake.uplinkReport(id)
		}
		writeJSON(w, http.StatusOK, reports)
	})
	server := httptest.NewServer(mux)

	stack := &testStack{
		t: t, cfg: cfg, store: database, auth: authService, bus: bus, manager: manager,
		identity: gatewayIdentity, server: server, api: apiServer, fakes: []*fakeWorker{fake}, cancel: cancel,
	}
	cleanup := func() {
		server.Close()
		cancel()
		manager.Close()
		fake.close()
		_ = database.Close()
	}
	return stack, fake, cleanup
}
